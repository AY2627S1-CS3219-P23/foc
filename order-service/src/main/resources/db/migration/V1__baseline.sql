-- One row per errand request. status holds an OrderStates name; a state
-- added to OrderStates needs a migration that replaces this CHECK.
create table requests (
    id bigint generated by default as identity,
    requester_id bigint not null,
    courier_id bigint,
    supplier_id bigint not null,
    supplier_name text,
    dropoff_location text not null,
    item text not null,
    credit_amount integer not null,
    status text not null,
    deadline timestamp(6) with time zone not null,
    accepted_at timestamp(6) with time zone,
    collected_at timestamp(6) with time zone,
    arrived_at timestamp(6) with time zone,
    created_at timestamp(6) with time zone not null,
    version bigint not null,
    primary key (id),
    constraint requests_status_check check (status in (
        'PENDING', 'CREATED', 'ACCEPTED', 'COLLECTED', 'ARRIVED',
        'COMPLETED', 'CANCELLED', 'EXPIRED', 'REJECTED'))
);

-- Request events waiting to be published, written in the same transaction
-- as the request's state change (transactional outbox, a copy of
-- credit-service's D10).
create table outbox_event (
    event_id uuid not null,
    event_type varchar(255) not null,
    payload text not null,
    created_at timestamp(6) with time zone not null,
    sent_at timestamp(6) with time zone,
    next_attempt_at timestamp(6) with time zone,
    primary key (event_id)
);

-- the publisher's poll: unsent events, oldest first. Partial, so the
-- index stays small no matter how many sent rows accumulate (sent rows
-- are kept; Order has no purge).
create index idx_outbox_event_unsent on outbox_event (created_at) where sent_at is null;
