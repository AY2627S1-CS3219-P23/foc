-- one row per recipient of a consumed event (D4, F1.2); payload is the
-- event's business fields as JSON (Hibernate's LONGVARCHAR on PostgreSQL)
create table notifications (
    id bigint generated by default as identity,
    created_at timestamp(6) with time zone not null,
    event_id varchar(255) not null,
    event_type varchar(255) not null,
    occurred_at timestamp(6) with time zone not null,
    payload varchar(32600) not null,
    is_read boolean not null,
    recipient_id varchar(255) not null,
    constraint notifications_pkey primary key (id)
);

create index idx_notifications_recipient on notifications (recipient_id);

-- the dedupe inbox (D4, F2.1): the primary key rejects a duplicate event
-- id; processed_at is indexed for the retention purge (issue #137)
create table processed_events (
    event_id varchar(255) not null,
    processed_at timestamp(6) with time zone not null,
    constraint processed_events_pkey primary key (event_id)
);

create index idx_processed_events_processed_at on processed_events (processed_at);
